#!/usr/bin/env python3
"""
VoxCPM2 Audio Watermark Verification CLI Tool.
Detects whether an audio file was generated by VoxCPM2 Lightweight (Burmese + English).

Usage:
    python verify_audio.py <audio_path.wav>
"""

import os
import sys
import argparse
import soundfile as sf

# Add parent directory to path
SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, SCRIPT_DIR)

from voxcpm.watermark import detect_watermark


def verify_audio_file(filepath: str, verbose: bool = False):
    if not os.path.exists(filepath):
        print(f"❌ Error: File not found: {filepath}")
        return False

    print("=" * 65)
    print("   VoxCPM2 Audio Watermark & Authenticity Verification")
    print("=" * 65)
    print(f"📁 Target File   : {os.path.abspath(filepath)}")

    try:
        data, sr = sf.read(filepath)
    except Exception as e:
        print(f"❌ Error reading audio file: {e}")
        return False

    if data.ndim > 1:
        # Downmix stereo to mono for analysis
        data = data.mean(axis=1)

    duration = len(data) / sr
    print(f"⏱️ Duration      : {duration:.2f} seconds")
    print(f"🎚️ Sample Rate   : {sr} Hz")
    print(f"🔍 Analyzing frequency spectrum (19.5 kHz - 21.5 kHz near-ultrasound)...")

    # Run acoustic watermark detector
    res = detect_watermark(data, sr=sr)

    print("-" * 65)
    if res["detected"]:
        print("🎉 [RESULT] VERIFIED AUTHENTIC AI AUDIO!")
        print(f"  • Tool / Generator : {res.get('generator', 'VoxCPM2-Burmese-Light')}")
        print(f"  • Model Origin     : {res.get('model_id', 'minthura635/voxmmlite')}")
        print(f"  • Watermark Type   : Imperceptible High-Frequency Acoustic DSSS")
        print(f"  • Confidence Score : {res['confidence'] * 100:.1f}%")
        print(f"  • Sync Offset      : Sample #{res.get('sync_offset', 0)}")
        print(f"  • CRC16 Integrity  : {'Valid ✓' if res.get('crc_valid') else 'Degraded ⚠️'}")
        print("=" * 65)
        return True
    else:
        print("❌ [RESULT] NO VOXCPM2 WATERMARK DETECTED.")
        print(f"  • Confidence Score : {res['confidence'] * 100:.1f}%")
        print(f"  • Reason           : {res.get('details', 'No match')}")
        print("  • Conclusion       : This audio was NOT generated by VoxCPM2, or the watermark was stripped.")
        print("=" * 65)
        return False


def main():
    parser = argparse.ArgumentParser(description="Verify whether an audio was generated by VoxCPM2 Lightweight.")
    parser.add_argument("audio_path", type=str, help="Path to the WAV audio file to inspect.")
    parser.add_argument("-v", "--verbose", action="store_true", help="Show technical debug info.")

    args = parser.parse_args()
    verify_audio_file(args.audio_path, verbose=args.verbose)


if __name__ == "__main__":
    main()
